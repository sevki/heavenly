#!/usr/bin/env python3
"""Reference values for heavenly-orbit's perturbed propagation, written
independently of the Rust code:

* the Moon from DE440 (SPICE spkpos), for heavenly_orbit::analytic;
* the Celestial Intermediate Pole from SOFA's IAU 2006/2000A xy06 (pyerfa);
* zonal gravity J2..J6 from explicit Legendre polynomials (not the Rust
  recursion), checked here against finite differences of the potential;
* orbits integrated with fixed-step classical RK4 (not the Rust adaptive
  Dormand-Prince), each run twice at step h and h/2 to bound its own error.
  The full-model cases take the Sun and the Moon from DE440 and the pole from
  SOFA, so they also measure the cost of heavenly's analytic series.

The force model (EGM2008 zonals, Vallado's exponential atmosphere, a
cannonball in a cylindrical shadow) is the one documented in
heavenly_orbit::forces.

Usage: pip install spiceypy==8.4.0 pyerfa==2.0.1.5 numpy
       python3 generate_numerical.py <kernel-dir> > numerical_data.rs
(needs naif0012.tls and de440s.bsp in <kernel-dir>)
"""
import math
import os
import sys

import erfa
import numpy as np
import spiceypy as spice

kdir = sys.argv[1]
spice.furnsh(os.path.join(kdir, "naif0012.tls"))
spice.furnsh(os.path.join(kdir, "de440s.bsp"))

MU = 3.9860043550702266e14
MU_SUN = 1.3271244004127942e20
MU_MOON = 4.9028001184575496e12
RE = 6378137.0
FLAT = 1.0 / 298.257223563
OMEGA = 7.292115e-5
AU = 149597870700.0
P_SRP = 4.54e-6
CBAR = [-4.84165143790815e-4, 9.57161207093473e-7, 5.39965866638991e-7,
        6.86702913736681e-8, -1.49953927978527e-7]
J = [-c * math.sqrt(2 * n + 1) for n, c in zip(range(2, 7), CBAR)]

out = []
w = out.append
w("// @generated by tests/reference/generate_numerical.py. Do not edit.\n")
w(f"// SPICE {spice.tkvrsn('TOOLKIT')}, ERFA {erfa.__version__}, NumPy {np.__version__}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in np.asarray(xs).flatten()) + "]"


def et_of(tt):
    """TT seconds since J2000 -> TDB seconds since J2000 (SPICE ET)."""
    return spice.unitim(tt, "TT", "TDB")


# --- Moon (DE440) and pole (SOFA) -------------------------------------------
def moon(tt):
    p, _ = spice.spkpos("MOON", et_of(tt), "J2000", "NONE", "EARTH")
    return np.array(p) * 1e3


def sun(tt):
    p, _ = spice.spkpos("SUN", et_of(tt), "J2000", "NONE", "EARTH")
    return np.array(p) * 1e3


def cip(tt):
    x, y = erfa.xy06(2451545.0, tt / 86400.0)
    return np.array([x, y, math.sqrt(1 - x * x - y * y)])


# Every 3.7 days over 1950-2050.
tts = [(-50 * 365.25 + 3.7 * k) * 86400.0 for k in range(int(100 * 365.25 / 3.7))]
w("/// (TT seconds since J2000, DE440 geocentric Moon in J2000/GCRF, m)\n")
w("pub const MOON: &[(f64, [f64; 3])] = &[\n")
for tt in tts[::5]:
    w(f"    ({tt!r}, {fmt(moon(tt))}),\n")
w("];\n\n")
w("/// (TT seconds since J2000, CIP unit vector in GCRS from SOFA xy06)\n")
w("pub const POLE: &[(f64, [f64; 3])] = &[\n")
for tt in tts[::5]:
    w(f"    ({tt!r}, {fmt(cip(tt))}),\n")
w("];\n\n")


# --- Zonal gravity -----------------------------------------------------------
P = [
    lambda u: (3 * u**2 - 1) / 2,
    lambda u: (5 * u**3 - 3 * u) / 2,
    lambda u: (35 * u**4 - 30 * u**2 + 3) / 8,
    lambda u: (63 * u**5 - 70 * u**3 + 15 * u) / 8,
    lambda u: (231 * u**6 - 315 * u**4 + 105 * u**2 - 5) / 16,
]
DP = [
    lambda u: 3 * u,
    lambda u: (15 * u**2 - 3) / 2,
    lambda u: (140 * u**3 - 60 * u) / 8,
    lambda u: (315 * u**4 - 210 * u**2 + 15) / 8,
    lambda u: (1386 * u**5 - 1260 * u**3 + 210 * u) / 16,
]


def zonal_potential(r, pole, degree=6):
    rn = np.linalg.norm(r)
    u = r @ pole / rn
    return -MU / rn * sum(J[n - 2] * (RE / rn) ** n * P[n - 2](u) for n in range(2, degree + 1))


def zonal_accel(r, pole, degree=6):
    rn = np.linalg.norm(r)
    rhat = r / rn
    u = rhat @ pole
    a = np.zeros(3)
    for n in range(2, degree + 1):
        k = J[n - 2] * MU * RE**n / rn ** (n + 2)
        a += k * (((n + 1) * P[n - 2](u) + u * DP[n - 2](u)) * rhat - DP[n - 2](u) * pole)
    return a


rng = np.random.default_rng(5)
zonal_rows = []
for _ in range(40):
    r = rng.normal(size=3)
    r *= rng.uniform(6.5e6, 4.3e7) / np.linalg.norm(r)
    pole = np.array([0.0, 0.0, 1.0])
    a = zonal_accel(r, pole)
    # The gravitational potential is U = mu/r + zonal_potential, with the
    # acceleration a = +grad U.
    h = 1.0
    fd = np.array([(zonal_potential(r + h * e, pole) - zonal_potential(r - h * e, pole)) / (2 * h) for e in np.eye(3)])
    assert np.linalg.norm(fd - a) <= 1e-6 * np.linalg.norm(a) + 1e-12, (fd, a)
    zonal_rows.append((r, a, float(zonal_potential(r, pole))))
w("/// (position m, J2..J6 acceleration m/s^2, zonal potential J/kg) about the z axis\n")
w("pub const ZONAL: &[([f64; 3], [f64; 3], f64)] = &[\n")
for r, a, u in zonal_rows:
    w(f"    ({fmt(r)}, {fmt(a)}, {u!r}),\n")
w("];\n\n")


# --- Atmosphere --------------------------------------------------------------
LAYERS = [
    (0, 1.225, 7.249), (25, 3.899e-2, 6.349), (30, 1.774e-2, 6.682), (40, 3.972e-3, 7.554),
    (50, 1.057e-3, 8.382), (60, 3.206e-4, 7.714), (70, 8.770e-5, 6.549), (80, 1.905e-5, 5.799),
    (90, 3.396e-6, 5.382), (100, 5.297e-7, 5.877), (110, 9.661e-8, 7.263), (120, 2.438e-8, 9.473),
    (130, 8.484e-9, 12.636), (140, 3.845e-9, 16.149), (150, 2.070e-9, 22.523), (180, 5.464e-10, 29.740),
    (200, 2.789e-10, 37.105), (250, 7.248e-11, 45.546), (300, 2.418e-11, 53.628), (350, 9.518e-12, 53.298),
    (400, 3.725e-12, 58.515), (450, 1.585e-12, 60.828), (500, 6.967e-13, 63.822), (600, 1.454e-13, 71.835),
    (700, 3.614e-14, 88.667), (800, 1.170e-14, 124.64), (900, 5.245e-15, 181.05), (1000, 3.019e-15, 268.00),
]


def density(h_m):
    h = h_m / 1e3
    base = max((l for l in LAYERS if h >= l[0]), key=lambda l: l[0], default=LAYERS[0])
    return base[1] * math.exp(-(h - base[0]) / base[2])


# --- Orbits -----------------------------------------------------------------
class Model:
    def __init__(self, tt0, zonal, true_pole, sun_moon, drag, srp):
        self.tt0, self.zonal, self.true_pole = tt0, zonal, true_pole
        self.sun_moon, self.drag, self.srp = sun_moon, drag, srp
        self.cache = {}

    def bodies(self, t):
        # The pole, Sun and Moon change slowly: tabulate them every 60 s and
        # interpolate (cubic), which errs by far less than a micrometre.
        k = math.floor(t / 60.0)
        f = t / 60.0 - k
        pts = [self.node(k + i) for i in (-1, 0, 1, 2)]
        c = [-f * (f - 1) * (f - 2) / 6, (f + 1) * (f - 1) * (f - 2) / 2, -(f + 1) * f * (f - 2) / 2, (f + 1) * f * (f - 1) / 6]
        return [sum(c[i] * pts[i][j] for i in range(4)) for j in range(3)]

    def node(self, k):
        if k not in self.cache:
            tt = self.tt0 + 60.0 * k
            pole = cip(tt) if self.true_pole else np.array([0.0, 0.0, 1.0])
            self.cache[k] = (pole, sun(tt), moon(tt))
        return self.cache[k]

    def accel(self, t, r, v):
        rn = np.linalg.norm(r)
        a = -MU * r / rn**3
        pole, s, m = self.bodies(t)
        pole = pole / np.linalg.norm(pole)
        if self.zonal:
            a += zonal_accel(r, pole, self.zonal)
        if self.drag:
            u = r @ pole / rn
            h = rn - RE * (1 - FLAT * u * u)
            rel = v - np.cross(OMEGA * pole, r)
            a += -0.5 * density(h) * self.drag * np.linalg.norm(rel) * rel
        if self.sun_moon:
            for body, mu in ((s, MU_SUN), (m, MU_MOON)):
                d = body - r
                a += mu * (d / np.linalg.norm(d) ** 3 - body / np.linalg.norm(body) ** 3)
        if self.srp:
            shat = s / np.linalg.norm(s)
            along = r @ shat
            if not (along < 0 and np.linalg.norm(r - along * shat) < RE):
                away = r - s
                d = np.linalg.norm(away)
                a += P_SRP * (AU / d) ** 2 * self.srp * away / d
        return a

    def run(self, y0, outputs, h):
        y = np.array(y0, dtype=float)
        t, res = 0.0, []

        def f(t, y):
            return np.concatenate([y[3:], self.accel(t, y[:3], y[3:])])

        for target in outputs:
            while t < target - 1e-9:
                dt = min(h, target - t)
                k1 = f(t, y)
                k2 = f(t + dt / 2, y + dt / 2 * k1)
                k3 = f(t + dt / 2, y + dt / 2 * k2)
                k4 = f(t + dt, y + dt * k3)
                y = y + dt / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
                t += dt
            res.append(y.copy())
        return res


def state_from_elements(a, e, i, raan, argp, nu):
    p = a * (1 - e * e)
    rpf = p / (1 + e * math.cos(nu)) * np.array([math.cos(nu), math.sin(nu), 0.0])
    vpf = math.sqrt(MU / p) * np.array([-math.sin(nu), e + math.cos(nu), 0.0])
    def rz(t):
        c, s = math.cos(t), math.sin(t)
        return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])
    def rx(t):
        c, s = math.cos(t), math.sin(t)
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    m = rz(raan) @ rx(i) @ rz(argp)
    return np.concatenate([m @ rpf, m @ vpf])


d = math.radians
TT0 = 836_000_000.0  # 2026-06-29, about
CASES = [
    # name, elements, (zonal degree, true pole, sun+moon, Cd*A/m, Cr*A/m), span s, step s, outputs
    ("leo_zonal_fixed_pole", (RE + 500e3, 0.001, d(51.6), d(30), d(40), d(10)), (6, False, False, 0, 0), 86400, 5.0, 24),
    ("leo_full", (RE + 400e3, 0.0005, d(51.6), d(200), d(80), d(0)), (6, True, True, 0.005, 0.006), 86400, 5.0, 24),
    ("sso_full", (RE + 700e3, 0.001, d(98.2), d(120), d(90), d(45)), (6, True, True, 0.002, 0.003), 3 * 86400, 10.0, 36),
    ("molniya", (26_600e3, 0.74, d(63.4), d(300), d(270), d(0)), (6, True, True, 0, 0.01), 7 * 86400, 20.0, 28),
    ("geo", (42_164e3, 0.0002, d(0.05), d(0), d(0), d(0)), (6, True, True, 0, 0.02), 30 * 86400, 60.0, 30),
]
w("/// (name, TT0 s since J2000, [zonal degree, true pole 0/1, Sun+Moon 0/1, Cd*A/m, Cr*A/m],\n")
w("///  initial state [m, m/s], [(seconds after TT0, state)], RK4 self-convergence bound m)\n")
w("pub const ORBITS: &[(&str, f64, [f64; 5], [f64; 6], &[(f64, [f64; 6])], f64)] = &[\n")
for name, el, (deg, tp, sm, cd, cr), span, h, n in CASES:
    y0 = state_from_elements(*el)
    model = Model(TT0, deg, tp, sm, cd, cr)
    outs = [float(span * (k + 1) / n) for k in range(n)]
    coarse = model.run(y0, outs, h)
    fine = model.run(y0, outs, h / 2)
    bound = float(max(np.linalg.norm(a[:3] - b[:3]) for a, b in zip(coarse, fine)))
    print(f"{name}: RK4 h vs h/2 differ by {bound:.2e} m", file=sys.stderr)
    w(f'    ("{name}", {TT0!r}, {fmt([deg, int(tp), int(sm), cd, cr])}, {fmt(y0)}, &[\n')
    for t, y in zip(outs, fine):
        w(f"        ({t!r}, {fmt(y)}),\n")
    w(f"    ], {bound!r}),\n")
w("];\n")
sys.stdout.write("".join(out))
