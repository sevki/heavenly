#!/usr/bin/env python3
"""Generate kernels and reference values for heavenly-spice's tests.

Writes, into tests/data/:
  * synthetic.bsp      SPK with type 2 and type 3 segments (little-endian)
  * synthetic_be.bsp   the same file converted to big-endian
  * synthetic.bpc      binary PCK type 2 for frame class 31008
and prints tests/reference/data.rs with SPICE's answers for those kernels
and for the real de440s.bsp / moon_pa_de440_200625.bpc.

Usage:
    pip install spiceypy==8.4.0 numpy
    python3 generate.py <kernel-dir> > data.rs
where <kernel-dir> holds naif0012.tls, de440s.bsp,
moon_pa_de440_200625.bpc and moon_de440_250416.tf.
"""
import os
import random
import struct
import sys

import numpy as np
import spiceypy as spice

kdir = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
data_dir = os.path.join(here, "..", "data")
os.makedirs(data_dir, exist_ok=True)
rng = random.Random(7)

spice.furnsh(os.path.join(kdir, "moon_de440_250416.tf"))
DAY = 86400.0
FIRST, LAST = -400 * DAY, 400 * DAY


def chebyshev_records(n, degree, components, scales):
    out = []
    for _ in range(n):
        for c in range(components):
            s = scales[c]
            out += [rng.uniform(-1, 1) * s / (k + 1) ** 2 for k in range(degree + 1)]
    return out


# --- Synthetic SPK -------------------------------------------------------
spk_path = os.path.join(data_dir, "synthetic.bsp")
if os.path.exists(spk_path):
    os.remove(spk_path)
h = spice.spkopn(spk_path, "heavenly-spice test", 0)
# Earth-Moon barycentre (3) about the SSB (0): type 3, 16 records, degree 9.
n, deg = 16, 9
spice.spkw03(h, 3, 0, "J2000", FIRST, LAST, "EMB type 3", (LAST - FIRST) / n, n, deg,
             chebyshev_records(n, deg, 6, [1.5e8] * 3 + [30.0] * 3), FIRST)
# Earth (399) about EMB: type 2, 32 records, degree 12.
n, deg = 32, 12
spice.spkw02(h, 399, 3, "J2000", FIRST, LAST, "Earth type 2", (LAST - FIRST) / n, n, deg,
             chebyshev_records(n, deg, 3, [5e3] * 3), FIRST)
# Moon (301) about EMB: type 2 over the full window ...
n, deg = 40, 11
spice.spkw02(h, 301, 3, "J2000", FIRST, LAST, "Moon type 2", (LAST - FIRST) / n, n, deg,
             chebyshev_records(n, deg, 3, [4e5] * 3), FIRST)
# ... and a later, overlapping segment that must take precedence in [0, 50 d].
n, deg = 5, 8
spice.spkw02(h, 301, 3, "J2000", 0.0, 50 * DAY, "Moon override", 10 * DAY, n, deg,
             chebyshev_records(n, deg, 3, [4e5] * 3), 0.0)
spice.spkcls(h)


def to_big_endian(src, dst):
    """Rewrite a little-endian DAF as BIG-IEEE, word by word."""
    b = bytearray(open(src, "rb").read())
    nd, ni = struct.unpack_from("<ii", b, 8)
    fward, bward, free = struct.unpack_from("<iii", b, 76)
    out = bytearray(b)
    struct.pack_into(">ii", out, 8, nd, ni)
    struct.pack_into(">iii", out, 76, fward, bward, free)
    out[88:96] = b"BIG-IEEE"
    nrec = len(b) // 1024
    summary, name = set(), set()
    rec = fward
    while rec:
        summary.add(rec)
        name.add(rec + 1)
        rec = int(struct.unpack_from("<d", b, (rec - 1) * 1024)[0])
    ss = nd + (ni + 1) // 2
    for r in range(2, nrec + 1):
        base = (r - 1) * 1024
        if r in name:
            continue
        if r in summary:
            for k in range(3):
                struct.pack_into(">d", out, base + 8 * k, struct.unpack_from("<d", b, base + 8 * k)[0])
            count = int(struct.unpack_from("<d", b, base + 16)[0])
            for i in range(count):
                s = base + 24 + i * ss * 8
                for k in range(nd):
                    struct.pack_into(">d", out, s + 8 * k, struct.unpack_from("<d", b, s + 8 * k)[0])
                for k in range(ni):
                    o = s + 8 * nd + 4 * k
                    struct.pack_into(">i", out, o, struct.unpack_from("<i", b, o)[0])
            continue
        for k in range(128):
            struct.pack_into(">d", out, base + 8 * k, struct.unpack_from("<d", b, base + 8 * k)[0])
    open(dst, "wb").write(bytes(out))


be_path = os.path.join(data_dir, "synthetic_be.bsp")
to_big_endian(spk_path, be_path)

# --- Synthetic binary PCK -------------------------------------------------
pck_path = os.path.join(data_dir, "synthetic.bpc")
if os.path.exists(pck_path):
    os.remove(pck_path)
h = spice.pckopn(pck_path, "heavenly-spice test", 0)
n, deg = 24, 10
cdata = []
for i in range(n):
    for c, (const, scale) in enumerate(((0.07, 0.01), (0.42, 0.01), (3.0 + i * 0.9, 0.5))):
        cdata += [const + rng.uniform(-1, 1) * scale] + [rng.uniform(-1, 1) * scale / (k + 1) ** 2 for k in range(1, deg + 1)]
spice.pckw02(h, 31008, "J2000", FIRST, LAST, "synthetic MOON_PA", (LAST - FIRST) / n, n, deg, cdata, FIRST)
spice.pckcls(h)

# --- Reference values ------------------------------------------------------
out = []
w = out.append
w("// @generated by tests/reference/generate.py. Do not edit.\n")
w(f"// SPICE {spice.tkvrsn('TOOLKIT')}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in np.asarray(xs).flatten()) + "]"


def states(kernel, pairs, ets):
    spice.furnsh(kernel)
    rows = []
    for et in ets:
        for t, o in pairs:
            st, _ = spice.spkgeo(t, et, "J2000", o)
            rows.append((t, o, et, st))
    spice.unload(kernel)
    return rows


pairs = [(301, 399), (399, 0), (0, 301), (3, 3), (399, 301), (3, 0)]
ets = [rng.uniform(FIRST, LAST) for _ in range(40)]
ets += [FIRST, LAST, 0.0, 25 * DAY, 50 * DAY, 10 * DAY, (LAST - FIRST) / 32 + FIRST]
w("/// (target, observer, ET, [km, km/s]) from SPICE spkgeo on synthetic.bsp.\n")
w("pub const SYNTHETIC_STATES: &[(i32, i32, f64, [f64; 6])] = &[\n")
for t, o, et, st in states(spk_path, pairs, ets):
    w(f"    ({t}, {o}, {et!r}, {fmt(st)}),\n")
w("];\n\n")

spice.furnsh(pck_path)
w("/// (ET, 6x6 state transform MOON_PA_DE440 -> J2000, row-major) from SPICE sxform on synthetic.bpc.\n")
w("pub const SYNTHETIC_PCK: &[(f64, [f64; 36])] = &[\n")
for et in ets:
    w(f"    ({et!r}, {fmt(spice.sxform('MOON_PA_DE440', 'J2000', et))}),\n")
w("];\n\n")
spice.unload(pck_path)

w("/// MOON_ME_DE440_ME421 -> MOON_PA_DE440 rotation, row-major, from SPICE pxform.\n")
w(f"pub const MOON_ME_TO_PA: [f64; 9] = {fmt(spice.pxform('MOON_ME_DE440_ME421', 'MOON_PA_DE440', 0.0))};\n\n")

# Real kernels.
spice.furnsh(os.path.join(kdir, "naif0012.tls"))
spice.furnsh(os.path.join(kdir, "de440s.bsp"))
spice.furnsh(os.path.join(kdir, "moon_pa_de440_200625.bpc"))
real_ets = [spice.str2et(f"{y}-{m:02d}-15 12:00:00 TDB") for y in range(1900, 2141, 8) for m in (1, 7)]
w("/// (target, observer, ET, [km, km/s]) from SPICE spkgeo on de440s.bsp.\n")
w("pub const DE440S_STATES: &[(i32, i32, f64, [f64; 6])] = &[\n")
for et in real_ets:
    for t, o in ((301, 399), (399, 0), (4, 0), (10, 399)):
        st, _ = spice.spkgeo(t, et, "J2000", o)
        w(f"    ({t}, {o}, {et!r}, {fmt(st)}),\n")
w("];\n\n")
w("/// (ET, 6x6 state transform MOON_PA_DE440 -> J2000) from SPICE sxform on moon_pa_de440_200625.bpc.\n")
w("pub const DE440_MOON_PA: &[(f64, [f64; 36])] = &[\n")
for et in real_ets:  # all within the bpc's 1550-2650 coverage
    w(f"    ({et!r}, {fmt(spice.sxform('MOON_PA_DE440', 'J2000', et))}),\n")
w("];\n")

sys.stdout.write("".join(out))
