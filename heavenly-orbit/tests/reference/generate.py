#!/usr/bin/env python3
"""Reference values for heavenly-orbit from SPICE (spiceypy):
prop2b (two-body propagation), conics (elements -> state) and
oscelt (state -> elements). No kernels are needed.

Usage: pip install spiceypy==8.4.0 && python3 generate.py > data.rs
"""
import math
import random
import sys

import spiceypy as spice

rng = random.Random(11)
GM_EARTH = 398600.43550702266  # km^3/s^2, DE440
GM_SUN = 132712440041.27942
out = []
w = out.append
w("// @generated by tests/reference/generate.py. Do not edit.\n")
w(f"// SPICE {spice.tkvrsn('TOOLKIT')}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in xs) + "]"


def random_elements(kind, gm):
    if kind == "leo":
        rp, e = rng.uniform(6.6e3, 8e3), rng.uniform(0, 0.02)
    elif kind == "heo":
        rp, e = rng.uniform(6.6e3, 2e4), rng.uniform(0.3, 0.95)
    elif kind == "near_parabolic":
        rp, e = rng.uniform(7e3, 5e4), rng.choice([0.999, 0.9999, 1.0001, 1.001])
    elif kind == "hyperbolic":
        rp, e = rng.uniform(7e3, 1e5), rng.uniform(1.05, 5.0)
    else:  # heliocentric
        rp, e = rng.uniform(5e7, 5e8), rng.uniform(0, 0.9)
    return [rp, e, rng.uniform(0.01, math.pi - 0.01), rng.uniform(0, 2 * math.pi),
            rng.uniform(0, 2 * math.pi), rng.uniform(-2, 2), 0.0, gm]


# --- prop2b -----------------------------------------------------------------
w("/// (GM km^3/s^2, initial state [km, km/s], dt s, final state) from SPICE prop2b.\n")
w("pub const PROP2B: &[(f64, [f64; 6], f64, [f64; 6])] = &[\n")
cases = []
for kind, gm in [("leo", GM_EARTH)] * 15 + [("heo", GM_EARTH)] * 15 + [("near_parabolic", GM_EARTH)] * 12 + \
        [("hyperbolic", GM_EARTH)] * 15 + [("helio", GM_SUN)] * 10:
    el = random_elements(kind, gm)
    s0 = spice.conics(el, 0.0)
    scale = 86400.0 if gm == GM_EARTH else 365.25 * 86400.0
    for dt in (rng.uniform(-1, 1) * scale, rng.uniform(5, 50) * scale, -rng.uniform(0, 0.01) * scale):
        cases.append((gm, s0, dt, spice.prop2b(gm, s0, dt)))
for gm, s0, dt, s1 in cases:
    w(f"    ({gm!r}, {fmt(s0)}, {dt!r}, {fmt(s1)}),\n")
w("];\n\n")

# --- conics -----------------------------------------------------------------
w("/// (elements [rp km, e, i, node, argp, M0, t0 ET, GM], ET, state) from SPICE conics.\n")
w("pub const CONICS: &[([f64; 8], f64, [f64; 6])] = &[\n")
for kind, gm in [("leo", GM_EARTH)] * 10 + [("heo", GM_EARTH)] * 10 + [("hyperbolic", GM_EARTH)] * 10 + [("helio", GM_SUN)] * 5:
    el = random_elements(kind, gm)
    el[6] = rng.uniform(-3e8, 3e8)
    et = el[6] + rng.uniform(-2, 2) * 86400.0
    w(f"    ({fmt(el)}, {et!r}, {fmt(spice.conics(el, et))}),\n")
# Exactly circular and exactly parabolic orbits.
for e in (0.0, 1.0):
    el = [7000.0, e, 0.9, 1.1, 0.4, 0.3, 1e8, GM_EARTH]
    for dt in (0.0, 3600.0, -5000.0):
        w(f"    ({fmt(el)}, {el[6] + dt!r}, {fmt(spice.conics(el, el[6] + dt))}),\n")
w("];\n\n")

# --- oscelt -----------------------------------------------------------------
w("/// (state [km, km/s], ET, GM, elements [rp, e, i, node, argp, M0, t0, GM]) from SPICE oscelt.\n")
w("pub const OSCELT: &[([f64; 6], f64, f64, [f64; 8])] = &[\n")
for kind, gm in [("leo", GM_EARTH)] * 5 + [("heo", GM_EARTH)] * 10 + [("hyperbolic", GM_EARTH)] * 10 + [("helio", GM_SUN)] * 5:
    el = random_elements(kind, gm)
    if kind == "leo":
        el[1] = rng.uniform(0.001, 0.02)  # keep away from circular for unambiguous angles
    et = rng.uniform(-3e8, 3e8)
    el[6] = et
    st = spice.conics(el, et)
    w(f"    ({fmt(st)}, {et!r}, {gm!r}, {fmt(spice.oscelt(st, et, gm))}),\n")
w("];\n")

sys.stdout.write("".join(out))
