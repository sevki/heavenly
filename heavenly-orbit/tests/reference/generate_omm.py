#!/usr/bin/env python3
"""OMM reference values: the official SGP4 verification TLEs, converted to
OMM by the `sgp4` package (`exporter.export_omm`), written as KVN, JSON and
CSV, and propagated with Vallado's C++ from the OMM fields through
`sgp4.omm.initialize` (WGS-72, improved mode).

Usage: pip install sgp4==2.27
       python3 generate_omm.py > omm_data.rs
"""
import csv
import io
import json
import os

import sgp4
from sgp4 import omm
from sgp4.api import WGS72, Satrec, accelerated
from sgp4.exporter import export_omm

assert accelerated, "need the C++ (accelerated) sgp4 build"

lines = [l.rstrip("\n") for l in open(os.path.join(os.path.dirname(sgp4.__file__), "SGP4-VER.TLE"))]
lines = [l for l in lines if l and not l.startswith("#")]
records = []
for i in range(0, len(lines), 2):
    l1, l2 = lines[i][:69], lines[i + 1][:69]
    start, stop, step = (float(x) for x in lines[i + 1][69:].split())
    sat = Satrec.twoline2rv(l1, l2, WGS72)
    if sat.intldesg.strip():
        fields = export_omm(sat, f"VER {sat.satnum}")
    else:  # 11801 has no international designator
        sat.intldesg = "80000A"
        fields = export_omm(sat, f"VER {sat.satnum}")
        fields["OBJECT_ID"] = ""
    records.append((l1, l2, start, stop, step, fields))

keys = list(records[0][5].keys())

# KVN: one message per object, each with the standard header.
kvn = []
for *_, f in records:
    kvn.append("CCSDS_OMM_VERS = 2.0")
    kvn.append("COMMENT generated by generate_omm.py from SGP4-VER.TLE")
    kvn.append("CREATION_DATE = 2026-11-20T00:00:00")
    kvn.append("ORIGINATOR = heavenly tests")
    for k in keys:
        kvn.append(f"{k} = {f[k]}")
    kvn.append("")
kvn_text = "\n".join(kvn)
json_text = json.dumps([r[5] for r in records], indent=1)
buf = io.StringIO()
w = csv.DictWriter(buf, fieldnames=keys, lineterminator="\n")
w.writeheader()
for r in records:
    w.writerow(r[5])
csv_text = buf.getvalue()


def f(x):
    x = float(x)
    return "f64::NAN" if x != x else repr(x)


def arr(xs):
    return "[" + ", ".join(f(x) for x in xs) + "]"


out = []
out.append("// @generated by tests/reference/generate_omm.py. Do not edit.\n")
out.append(f"// sgp4 {sgp4.__version__} (Vallado C++)\n")
out.append("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")
out.append(f"pub const KVN: &str = {json.dumps(kvn_text)};\n\n")
out.append(f"pub const JSON: &str = {json.dumps(json_text)};\n\n")
out.append(f"pub const CSV: &str = {json.dumps(csv_text)};\n\n")
out.append("/// (TLE line 1, line 2, NORAD id, init error, [(tsince min, error, r km, v km/s)])\n")
out.append("/// propagated from the OMM fields with omm.initialize.\n")
out.append("pub const STATES: &[(&str, &str, u32, u8, &[(f64, u8, [f64; 3], [f64; 3])])] = &[\n")
for l1, l2, start, stop, step, fields in records:
    s = Satrec()
    omm.initialize(s, {k: str(v) for k, v in fields.items()})
    init_error = s.error
    rows = []
    if init_error == 0:
        t = start
        while (step > 0 and t <= stop) or (step < 0 and t >= stop):
            e, r, v = s.sgp4_tsince(t)
            rows.append(f"({f(t)}, {e}, {arr(r)}, {arr(v)})")
            if e != 0:
                break
            t += step
    out.append(f"    ({json.dumps(l1)}, {json.dumps(l2)}, {fields['NORAD_CAT_ID']}, {init_error}, &[\n")
    out.extend(f"        {r},\n" for r in rows)
    out.append("    ]),\n")
out.append("];\n")
print("".join(out), end="")
