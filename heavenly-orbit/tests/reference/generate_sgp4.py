#!/usr/bin/env python3
"""SGP4 reference values from Vallado's C++ implementation, through the
`sgp4` Python package (its `Satrec` wraps the C++ code), over the official
verification TLEs (SGP4-VER.TLE, shipped with the package).

Usage: pip install sgp4==2.27
       python3 generate_sgp4.py > sgp4_data.rs
"""
import os

import sgp4
from sgp4.api import WGS72, WGS72OLD, WGS84, Satrec, accelerated

assert accelerated, "need the C++ (accelerated) sgp4 build"

out = []
w = out.append
w("// @generated by tests/reference/generate_sgp4.py. Do not edit.\n")
w(f"// sgp4 {sgp4.__version__} (Vallado C++)\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def f(x):
    x = float(x)
    return "f64::NAN" if x != x else repr(x)


def arr(xs):
    return "[" + ", ".join(f(x) for x in xs) + "]"


cases = []
lines = [l.rstrip("\n") for l in open(os.path.join(os.path.dirname(sgp4.__file__), "SGP4-VER.TLE"))]
lines = [l for l in lines if l and not l.startswith("#")]
for i in range(0, len(lines), 2):
    l1, l2 = lines[i], lines[i + 1]
    start, stop, step = (float(x) for x in l2[69:].split())
    cases.append((l1[:69], l2[:69], start, stop, step))

GRAV = {"Wgs72": WGS72, "Wgs72Old": WGS72OLD, "Wgs84": WGS84}
MODES = [("Wgs72", "i"), ("Wgs72", "a"), ("Wgs84", "i"), ("Wgs72Old", "a")]

w("/// (line 1, line 2, catalogue number, [bstar, ecco, inclo, nodeo, argpo, mo, no_kozai, ndot, nddot])\n")
w("/// as the reference parses them (angles in rad, rates in rad/min^n).\n")
w("pub const PARSED: &[(&str, &str, u32, [f64; 9])] = &[\n")
for l1, l2, *_ in cases:
    t = Satrec.twoline2rv(l1, l2, WGS72)
    fields = [t.bstar, t.ecco, t.inclo, t.nodeo, t.argpo, t.mo, t.no_kozai, t.ndot, t.nddot]
    w(f"    ({l1!r}, {l2!r}, {t.satnum}, {arr(fields)}),\n".replace("'", '"'))
w("];\n\n")

w("/// (line 1, line 2, gravity, opsmode, SGP4 epoch in days since 1950,\n")
w("///  init error, [(tsince min, error, r km, v km/s)])\n")
w("pub const VERIFICATION: &[(&str, &str, &str, &str, f64, u8, &[(f64, u8, [f64; 3], [f64; 3])])] = &[\n")
for grav, mode in MODES:
    for l1, l2, start, stop, step in cases:
        t = Satrec.twoline2rv(l1, l2, GRAV[grav])
        s = Satrec()
        s.sgp4init(GRAV[grav], mode, t.satnum, t.jdsatepoch + t.jdsatepochF - 2433281.5,
                   t.bstar, t.ndot, t.nddot, t.ecco, t.argpo, t.inclo, t.mo, t.no_kozai, t.nodeo)
        epoch = t.jdsatepoch + t.jdsatepochF - 2433281.5
        rows = []
        times = []
        k = 0
        while True:
            ts = start + k * step
            if (step > 0 and ts > stop) or (step < 0 and ts < stop):
                break
            times.append(ts)
            k += 1
        if times[-1] != stop:
            times.append(stop)
        init_error = s.error
        if init_error == 0:
            for ts in times:
                e, r, v = s.sgp4_tsince(ts)
                rows.append(f"({f(ts)}, {e}, {arr(r)}, {arr(v)})")
                if e != 0:
                    break
        w(f"    ({l1!r}, {l2!r}, {grav!r}, {mode!r}, {f(epoch)}, {init_error}, &[\n".replace("'", '"'))
        for r in rows:
            w(f"        {r},\n")
        w("    ]),\n")
w("];\n\n")

print("".join(out), end="")
