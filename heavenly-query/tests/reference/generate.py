#!/usr/bin/env python3
"""Light-time reference values for heavenly-query, from SPICE spkezr with
the converged Newtonian corrections CN (reception) and XCN (transmission).

Uses heavenly-spice's committed synthetic kernel, plus de440s.bsp for the
real-ephemeris cases.

Usage: pip install spiceypy==8.4.0 numpy && python3 generate.py <kernel-dir> > data.rs
"""
import os
import random
import sys

import numpy as np
import spiceypy as spice

here = os.path.dirname(os.path.abspath(__file__))
kdir = sys.argv[1]
rng = random.Random(23)
out = []
w = out.append
w("// @generated by tests/reference/generate.py. Do not edit.\n")
w(f"// SPICE {spice.tkvrsn('TOOLKIT')}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in np.asarray(xs).flatten()) + "]"


def rows(name, doc, kernel, pairs, ets):
    spice.furnsh(kernel)
    w(f"/// {doc}\n/// (target, observer, ET, correction (\"CN\"/\"XCN\"), state [km, km/s], light time s)\n")
    w(f"pub const {name}: &[(i32, i32, f64, &str, [f64; 6], f64)] = &[\n")
    for et in ets:
        for t, o in pairs:
            for corr in ("CN", "XCN"):
                st, lt = spice.spkezr(str(t), et, "J2000", corr, str(o))
                w(f'    ({t}, {o}, {et!r}, "{corr}", {fmt(st)}, {lt!r}),\n')
    w("];\n\n")
    spice.unload(kernel)


DAY = 86400.0
rows("SYNTHETIC", "SPICE spkezr on heavenly-spice's synthetic.bsp.",
     os.path.join(here, "../../../heavenly-spice/tests/data/synthetic.bsp"),
     [(301, 399), (399, 301), (3, 0), (0, 3)],
     [rng.uniform(-390 * DAY, 390 * DAY) for _ in range(12)])
rows("DE440S", "SPICE spkezr on de440s.bsp (Moon, Sun, Mars barycentre from the Earth).",
     os.path.join(kdir, "de440s.bsp"),
     [(301, 399), (10, 399), (4, 399)],
     [rng.uniform(-3e9, 3e9) for _ in range(12)])
sys.stdout.write("".join(out))
