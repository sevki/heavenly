#!/usr/bin/env python3
"""EOP reference values from astropy's IERS readers, over excerpts of the
IERS files shipped in `astropy-iers-data` (pinned below):

* tests/data/finals2000A_2016.txt: finals2000A, 2016-07-01 .. 2017-06-30
  (around the 2016-12-31 leap second; Bulletin B present);
* tests/data/finals2000A_tail.txt: the last observed (Bulletin A) days and
  the first predictions;
* tests/data/eopc04_2016.txt: EOP 20 C04, 2016-07-01 .. 2017-06-30.

astropy interpolates linearly; heavenly uses four-point Lagrange on
UT1 - TAI. At the tabulated days the two must agree exactly; between them,
to within the linear-interpolation error.

Usage: pip install astropy==8.0.3 astropy-iers-data==0.2026.11.16.0.37.44
       python3 generate_eop.py <heavenly-geo/tests/data> > eop_data.rs
"""
import os
import random
import sys

import astropy
import astropy_iers_data
from astropy.time import Time
from astropy.utils import iers

src = os.path.join(os.path.dirname(astropy_iers_data.__file__), "data")
out_dir = sys.argv[1]


def excerpt(name, keep):
    lines = open(os.path.join(src, name)).read().splitlines(keepends=True)
    return "".join(l for l in lines if keep(l))


def finals_mjd(line):
    try:
        return float(line[7:15])
    except ValueError:
        return None


START, END = 57570, 57934  # 2016-07-01 .. 2017-06-30
finals = open(os.path.join(src, "finals2000A.all")).read().splitlines(keepends=True)
with open(os.path.join(out_dir, "finals2000A_2016.txt"), "w") as f:
    f.writelines(l for l in finals if START <= finals_mjd(l) <= END)
# The tail: 40 days before the first prediction, 40 after.
valued = [l for l in finals if len(l) > 68 and l[57] != " "]
p0 = next(i for i, l in enumerate(valued) if l[16] == "P" or l[57] == "P")
with open(os.path.join(out_dir, "finals2000A_tail.txt"), "w") as f:
    f.writelines(valued[p0 - 40 : p0 + 40])
c04 = open(os.path.join(src, "eopc04.1962-now")).read().splitlines(keepends=True)
with open(os.path.join(out_dir, "eopc04_2016.txt"), "w") as f:
    f.writelines(l for l in c04 if l.startswith("#") or START <= float(l.split()[4]) <= END)

w = sys.stdout.write
w("// @generated by tests/reference/generate_eop.py. Do not edit.\n")
w(f"// astropy {astropy.__version__}, astropy-iers-data {astropy_iers_data.__version__}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, dead_code)]\n\n")

rng = random.Random(7)


def table(name, reader, full, excerpt_path):
    # astropy reads the full file (its finals reader needs a predicted row,
    # which the 2016 excerpt has none of); interpolation only uses the
    # neighbouring days, so the values are those of the excerpt.
    t = reader.open(os.path.join(src, full))
    days = [finals_mjd(l) if full.startswith("finals") else float(l.split()[4])
            for l in open(excerpt_path) if not l.startswith("#")]
    lo, hi = min(days), max(days)
    mjds = [lo + k for k in range(0, int(hi - lo) + 1, 7)]
    mjds += [rng.uniform(lo, hi) for _ in range(150)]
    # Around the leap second at the end of 2016-12-31 (MJD 57753).
    mjds += [57753 + f for f in (0.25, 0.5, 0.9, 0.999, 0.99999)] + [57754.0, 57754.00001, 57754.5]
    mjds = [m for m in mjds if lo <= m < hi]
    w(f"/// (UTC, node?, UT1-UTC s, x arcsec, y arcsec) from astropy {reader.__name__}.\n")
    w(f"pub const {name}: &[(&str, bool, f64, f64, f64)] = &[\n")
    for m in mjds:
        tm = Time(m, format="mjd", scale="utc")
        iso = tm.isot  # millisecond precision
        exact = Time(iso, scale="utc")
        ut1 = t.ut1_utc(exact).to_value("s")
        x, y = (q.to_value("arcsec") for q in t.pm_xy(exact))
        w(f'    ("{iso}Z", {str(m == int(m)).lower()}, {float(ut1)!r}, {float(x)!r}, {float(y)!r}),\n')
    w("];\n\n")


table("FINALS_2016", iers.IERS_A, "finals2000A.all", os.path.join(out_dir, "finals2000A_2016.txt"))
table("FINALS_TAIL", iers.IERS_A, "finals2000A.all", os.path.join(out_dir, "finals2000A_tail.txt"))
table("C04_2016", iers.IERS_B, "eopc04.1962-now", os.path.join(out_dir, "eopc04_2016.txt"))
w(f'/// First predicted day of the tail excerpt.\npub const FIRST_PREDICTED: &str = "{Time(float(valued[p0][7:15]), format="mjd", scale="utc").isot}Z";\n')
