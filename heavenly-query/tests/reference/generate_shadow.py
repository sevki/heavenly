#!/usr/bin/env python3
"""Sun and eclipse reference values for heavenly-query, from SPICE:

* SUN: the geometric geocentric Sun (spkezr SUN wrt EARTH, J2000, NONE) on
  de440s, to measure `AnalyticSun`;
* ECLIPSES: eclipse intervals from gfoclt, with the Earth and the Sun as
  pck00011 ellipsoids and no aberration correction, for satellites in
  two-body orbits. SPICE propagates each orbit with prop2b, which
  heavenly-orbit matches to 1e-12, and writes it to a temporary SPK
  (type 13, 30 s steps) for gfoclt to observe from.

Usage: pip install spiceypy==8.4.0 numpy
       python3 generate_shadow.py <kernel-dir> > shadow_data.rs
"""
import math
import os
import random
import sys
import tempfile

import numpy as np
import spiceypy as spice
import spiceypy.utils.support_types as stypes

kdir = sys.argv[1]
for k in ("naif0012.tls", "pck00011.tpc", "de440s.bsp"):
    spice.furnsh(os.path.join(kdir, k))

out = []
w = out.append
w("// @generated by tests/reference/generate_shadow.py. Do not edit.\n")
w(f"// SPICE {spice.tkvrsn('TOOLKIT')}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in np.asarray(xs).flatten()) + "]"


rng = random.Random(31)
w("/// (TDB seconds past J2000, geometric Sun from the Earth in J2000, km) from de440s.\n")
w("pub const SUN: &[(f64, [f64; 3])] = &[\n")
for _ in range(200):
    et = rng.uniform(-50, 50) * 365.25 * 86400.0
    pos, _ = spice.spkpos("SUN", et, "J2000", "NONE", "EARTH")
    w(f"    ({et!r}, {fmt(pos)}),\n")
w("];\n\n")

MU = 398600.435507  # km^3/s^2, DE440 (heavenly_orbit::gm::EARTH / 1e9)
DEG = math.pi / 180.0
SATS = [
    # name, start (UTC), days, [rp km, e, i, node, argp, M0], gfoclt step s
    ("LEO", "2026-06-21T00:00:00", 2.0, [6778.0, 0.0005, 51.6 * DEG, 40 * DEG, 0.0, 0.0], 30.0),
    ("GEO", "2026-03-18T00:00:00", 5.0, [42164.0, 0.0, 0.05 * DEG, 0.0, 0.0, 0.0], 60.0),
    ("HEO", "2026-09-22T00:00:00", 3.0, [7000.0, 0.70, 63.4 * DEG, 100 * DEG, 270 * DEG, 0.0], 30.0),
]

w("/// (name, elements [rp km, e, i, node, argp, M0, epoch ET, GM km^3/s^2],\n")
w("///  start ET, end ET, gfoclt ANY intervals, gfoclt FULL intervals)\n")
w("pub const ECLIPSES: &[(&str, [f64; 8], f64, f64, &[(f64, f64)], &[(f64, f64)])] = &[\n")
tmp = tempfile.mkdtemp()
for k, (name, start, days, el, step) in enumerate(SATS):
    et0 = spice.utc2et(start)
    et1 = et0 + days * 86400.0
    elts = el + [et0, MU]
    s0 = spice.conics(elts, et0)
    epochs = np.arange(et0 - 600.0, et1 + 600.0 + 1.0, 30.0)
    states = np.array([spice.prop2b(MU, s0, t - et0) for t in epochs])
    body = -900 - k
    path = os.path.join(tmp, f"{name}.bsp")
    h = spice.spkopn(path, name, 0)
    spice.spkw13(h, body, 399, "J2000", epochs[0], epochs[-1], name, 7, len(epochs), states, epochs)
    spice.spkcls(h)
    spice.furnsh(path)
    windows = {}
    for occ in ("ANY", "FULL"):
        cnfine = stypes.SPICEDOUBLE_CELL(2)
        spice.wninsd(et0, et1, cnfine)
        result = stypes.SPICEDOUBLE_CELL(2000)
        spice.gfoclt(occ, "EARTH", "ELLIPSOID", "IAU_EARTH", "SUN", "ELLIPSOID", "IAU_SUN",
                     "NONE", str(body), step, cnfine, result)
        windows[occ] = [spice.wnfetd(result, i) for i in range(spice.wncard(result))]
    spice.unload(path)
    pairs = lambda ws: "&[" + ", ".join(f"({a!r}, {b!r})" for a, b in ws) + "]"
    w(f'    ("{name}", {fmt(elts)}, {et0!r}, {et1!r}, {pairs(windows["ANY"])}, {pairs(windows["FULL"])}),\n')
w("];\n\n")
r = spice.bodvrd("EARTH", "RADII", 3)[1]
w(f"/// pck00011 Earth radii (equatorial, polar), km.\npub const EARTH_RADII_KM: (f64, f64) = ({float(r[0])!r}, {float(r[2])!r});\n")
sys.stdout.write("".join(out))
