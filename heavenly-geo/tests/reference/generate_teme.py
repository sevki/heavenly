#!/usr/bin/env python3
"""TEME reference values: GMST (IAU 1982) from SOFA (pyerfa) and
TEME -> ITRF from Skyfield, which follows Vallado et al. (2006).

Usage: pip install pyerfa==2.0.1.5 skyfield==1.55 numpy
       python3 generate_teme.py > teme_data.rs
"""
import math
import random

import erfa
import numpy as np
import skyfield
from skyfield.sgp4lib import TEME_to_ITRF

out = []
w = out.append
w("// @generated by tests/reference/generate_teme.py. Do not edit.\n")
w(f"// erfa {erfa.__version__}, skyfield {skyfield.__version__}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def f(x):
    return repr(float(x))


def arr(xs):
    return "[" + ", ".join(f(x) for x in xs) + "]"


rng = random.Random(4)

# GMST (IAU 1982) at UT1 Julian dates.
w("/// (UT1 JD, GMST82 rad) from SOFA iauGmst82.\n")
w("pub const GMST82: &[(f64, f64)] = &[\n")
for k in range(40):
    # Dyadic offsets from J2000 (multiples of 2^-16 day) are exact in f64.
    jd = 2451545.0 + rng.randrange(-28 * 365 * 65536, 50 * 365 * 65536) / 65536
    w(f"    ({f(jd)}, {f(erfa.gmst82(jd, 0.0))}),\n")
w("];\n\n")

# TEME -> ITRF at UTC=UT1 instants, with polar motion.
w("/// (UT1 JD, xp rad, yp rad, r TEME km, v TEME km/s, r ITRF km, v ITRF km/s)\n")
w("/// from Skyfield TEME_to_ITRF.\n")
w("pub const TEME_TO_ITRF: &[(f64, f64, f64, [f64; 3], [f64; 3], [f64; 3], [f64; 3])] = &[\n")
asec = math.pi / 180 / 3600
for k in range(20):
    jd = 2451545.0 + rng.randrange(-9000 * 65536, 12000 * 65536) / 65536
    xp, yp = rng.uniform(-0.3, 0.3) * asec, rng.uniform(-0.1, 0.6) * asec
    r = np.array([rng.uniform(-8e3, 8e3) for _ in range(3)])
    v = np.array([rng.uniform(-7, 7) for _ in range(3)])
    ri, vi = TEME_to_ITRF(jd, r, v * 86400.0, xp, yp)
    w(f"    ({f(jd)}, {f(xp)}, {f(yp)}, {arr(r)}, {arr(v)}, {arr(ri)}, {arr(vi / 86400.0)}),\n")
w("];\n")

print("".join(out), end="")
