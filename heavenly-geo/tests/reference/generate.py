#!/usr/bin/env python3
"""Generate reference values for heavenly-geo's validation tests.

Sources are independent of this crate:
  * SOFA, via pyerfa: geodetic conversion (gc2gd) and Earth orientation
    (c2t06a: full IAU 2006/2000A).
  * SPICE, via spiceypy with NAIF's pck00011.tpc and naif0012.tls:
    IAU_MOON and IAU_MARS orientation.

Usage:
    pip install pyerfa spiceypy
    curl -O https://naif.jpl.nasa.gov/pub/naif/generic_kernels/pck/pck00011.tpc
    curl -O https://naif.jpl.nasa.gov/pub/naif/generic_kernels/lsk/naif0012.tls
    python3 generate.py <kernel-dir> > data.rs
"""
import math
import random
import sys

import erfa
import spiceypy as spice
import warnings

warnings.simplefilter("ignore", erfa.ErfaWarning)  # 'dubious year' for future UTC

kernels = sys.argv[1] if len(sys.argv) > 1 else "."
spice.furnsh(f"{kernels}/pck00011.tpc")
spice.furnsh(f"{kernels}/naif0012.tls")

AS2R = math.pi / 180 / 3600
out = []
w = out.append
w("// @generated by tests/reference/generate.py. Do not edit.\n")
w(f"// pyerfa {erfa.__version__}, SPICE {spice.tkvrsn('TOOLKIT')}\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity)]\n\n")

# --- Geodetic: random points on and around WGS84 -------------------------
rng = random.Random(42)
rows = []
for _ in range(200):
    lat = math.asin(rng.uniform(-1, 1))
    lon = rng.uniform(-math.pi, math.pi)
    h = rng.choice([0.0, rng.uniform(-10e3, 10e3), rng.uniform(1e5, 4e7)])
    # The forward conversion is closed-form and exact to rounding, so the
    # sampled (lat, lon, h) is the ground truth for the inverse.
    xyz = erfa.gd2gc(1, lon, lat, h)
    rows.append((*xyz, lat, lon, h))
for lat, lon, h in ((math.pi / 2, 0.0, 0.0), (-math.pi / 2, 0.0, 43_247.686), (0.0, 0.0, 621_863.0)):
    rows.append((*erfa.gd2gc(1, lon, lat, h), lat, lon, h))
w("/// (x, y, z, latitude, longitude, height) on WGS84; x, y, z from SOFA gd2gc.\n")
w("pub const GEODETIC: &[[f64; 6]] = &[\n")
for r in rows:
    w("    [" + ", ".join(repr(float(v)) for v in r) + "],\n")
w("];\n\n")

# --- Earth orientation ----------------------------------------------------
w("/// (UTC string, UT1-UTC s, xp rad, yp rad, GCRS->ITRS matrix row-major), from SOFA c2t06a.\n")
w("pub const EARTH: &[(&str, f64, f64, f64, [f64; 9])] = &[\n")
for year in range(1980, 2051, 2):
    for (mo, d, hh, mm, ss) in ((1, 1, 0, 0, 0.0), (7, 15, 13, 47, 21.25)):
        dut1 = rng.uniform(-0.9, 0.9)
        xp = rng.uniform(-0.3, 0.3) * AS2R
        yp = rng.uniform(0.0, 0.6) * AS2R
        u1, u2 = erfa.dtf2d("UTC", year, mo, d, hh, mm, ss)
        a1, a2 = erfa.utctai(u1, u2)
        t1, t2 = erfa.taitt(a1, a2)
        b1, b2 = erfa.utcut1(u1, u2, dut1)
        m = erfa.c2t06a(t1, t2, b1, b2, xp, yp)
        s = f"{year:04d}-{mo:02d}-{d:02d}T{hh:02d}:{mm:02d}:{ss:05.2f}Z"
        w(f'    ("{s}", {dut1!r}, {xp!r}, {yp!r}, [' + ", ".join(repr(float(v)) for v in m.flatten()) + "]),\n")
w("];\n\n")

# --- IAU body models ------------------------------------------------------
for name, frame in (("MOON", "IAU_MOON"), ("MARS", "IAU_MARS")):
    w(f"/// (TDB seconds past J2000, ICRF->{frame} matrix row-major), from SPICE pxform.\n")
    w(f"pub const {name}: &[(f64, [f64; 9])] = &[\n")
    for year in range(1960, 2101, 5):
        et = (year - 2000) * 365.25 * 86400.0 + rng.uniform(0, 365.25 * 86400.0)
        m = spice.pxform("J2000", frame, et)
        w(f"    ({et!r}, [" + ", ".join(repr(float(v)) for v in m.flatten()) + "]),\n")
    w("];\n\n")

sys.stdout.write("".join(out))
