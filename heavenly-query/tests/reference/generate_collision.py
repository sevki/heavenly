#!/usr/bin/env python3
"""Reference probabilities of collision for heavenly-query, computed
independently of the Rust code: the encounter-plane basis by Gram-Schmidt
from the relative velocity and a fixed axis (the probability does not depend
on the in-plane orientation), and the 2-D Gaussian integrated over the
hard-body disc on a polar grid (Gauss-Legendre in radius, trapezoid in
angle), checked for convergence by doubling the grid.

Usage: pip install numpy && python3 generate_collision.py > collision_data.rs
"""
import math
import sys

import numpy as np

rng = np.random.default_rng(17)
out = []
w = out.append
w("// @generated by tests/reference/generate_collision.py. Do not edit.\n")
w("#![allow(clippy::approx_constant, clippy::excessive_precision, clippy::type_complexity, dead_code)]\n\n")


def fmt(xs):
    return "[" + ", ".join(repr(float(x)) for x in np.asarray(xs).flatten()) + "]"


def plane_basis(v):
    z = v / np.linalg.norm(v)
    t = np.array([0.0, 0.0, 1.0]) if abs(z[2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    x = t - (t @ z) * z
    x /= np.linalg.norm(x)
    return x, np.cross(z, x)


def disc_integral(m, c, radius, nr, nt):
    inv = np.linalg.inv(c)
    norm = 1.0 / (2 * math.pi * math.sqrt(np.linalg.det(c)))
    g, wg = np.polynomial.legendre.leggauss(nr)
    rho = 0.5 * radius * (g + 1)
    wr = 0.5 * radius * wg
    th = np.linspace(0, 2 * math.pi, nt, endpoint=False)
    rr, tt = np.meshgrid(rho, th, indexing="ij")
    px = rr * np.cos(tt) - m[0]
    py = rr * np.sin(tt) - m[1]
    q = inv[0, 0] * px * px + 2 * inv[0, 1] * px * py + inv[1, 1] * py * py
    f = norm * np.exp(-0.5 * q) * rr
    return float((f.sum(axis=1) * (2 * math.pi / nt)) @ wr)


def random_cov(scale):
    a = rng.normal(size=(3, 3)) * scale * rng.uniform(0.2, 1.0, size=3)
    return a @ a.T + np.eye(3) * (0.05 * scale) ** 2


rows = []
while len(rows) < 30:
    ra = rng.normal(size=3)
    ra *= 6.9e6 / np.linalg.norm(ra)
    va = np.cross(ra, rng.normal(size=3))
    va *= 7.5e3 / np.linalg.norm(va)
    vrel = rng.normal(size=3) * rng.uniform(100, 14_000) / math.sqrt(3)
    radius = rng.uniform(5, 50)
    ca = random_cov(rng.uniform(2, 15) * radius)
    cb = random_cov(rng.uniform(2, 15) * radius)
    # A miss across the relative velocity (the time of closest approach).
    x, y = plane_basis(vrel)
    s = math.sqrt(np.trace(ca + cb) / 3)
    miss = rng.uniform(0, 3) * s * (math.cos(len(rows)) * x + math.sin(len(rows)) * y)
    rb, vb = ra + miss, va + vrel
    c = ca + cb
    p2 = np.array([[x @ c @ x, x @ c @ y], [y @ c @ x, y @ c @ y]])
    if np.sqrt(np.linalg.eigvalsh(p2)).min() < 0.2 * radius:
        continue  # keep the grid comfortably resolved
    m2 = np.array([miss @ x, miss @ y])
    p = disc_integral(m2, p2, radius, 160, 512)
    p_fine = disc_integral(m2, p2, radius, 320, 1024)
    assert abs(p - p_fine) <= 1e-12 + 1e-10 * p_fine, (p, p_fine)
    rows.append((ra, va, ca, rb, vb, cb, radius, p_fine))

w("/// (position a m, velocity a m/s, position covariance a m^2 (row-major 3x3),\n")
w("///  position b, velocity b, covariance b, hard-body radius m, probability)\n")
w("pub const PC: &[([f64; 3], [f64; 3], [f64; 9], [f64; 3], [f64; 3], [f64; 9], f64, f64)] = &[\n")
for ra, va, ca, rb, vb, cb, radius, p in rows:
    w(f"    ({fmt(ra)}, {fmt(va)}, {fmt(ca)}, {fmt(rb)}, {fmt(vb)}, {fmt(cb)}, {radius!r}, {p!r}),\n")
w("];\n")
sys.stdout.write("".join(out))
